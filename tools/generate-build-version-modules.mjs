/**
 * Writes per-app build-version.ts from mfe-versions.json (visible version banners).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const versions = JSON.parse(readFileSync(join(root, 'mfe-versions.json'), 'utf8'));

const header = `// AUTO-GENERATED by tools/generate-build-version-modules.mjs — do not edit\n\n`;

function writeVersionFile(filePath, name, version) {
  const body = `${header}export const APP_BUILD_NAME = '${name}' as const;\nexport const APP_BUILD_VERSION = '${version}' as const;\n`;
  mkdirSync(dirname(filePath), { recursive: true });
  writeFileSync(filePath, body);
  console.log(`Wrote ${filePath}`);
}

const shellV = versions.shell;
if (!shellV) {
  console.error('mfe-versions.json missing shell');
  process.exit(1);
}
writeVersionFile(join(root, 'apps/shell/src/app/build-version.ts'), 'shell', shellV);

for (let i = 1; i <= 10; i++) {
  const name = `mfe${String(i).padStart(2, '0')}`;
  const v = versions[name];
  if (!v) {
    console.error(`mfe-versions.json missing ${name}`);
    process.exit(1);
  }
  writeVersionFile(
    join(root, `apps/${name}/src/app/remote-entry/build-version.ts`),
    name,
    v,
  );
}
